/* Generate the adopted settings; local drafts remain outside Git. */
'use strict';
const fs=require('node:fs'),path=require('node:path'),M=require('../assets/menu-layout');
function render(project){
 return '/* Adopted menu layout. Generated by scripts/adopt-menu-layout.js. */\n'+
  '(function(root){const config='+JSON.stringify(M.normalize(project),null,2)+';\n'+
  "if(typeof module==='object'&&module.exports)module.exports=config;else root.ParryMenuLayoutConfig=config;\n"+
  "})(typeof window==='undefined'?globalThis:window);\n";
}
if(require.main===module){
 const project=process.argv[2]?JSON.parse(fs.readFileSync(path.resolve(process.argv[2]),'utf8')):M.defaults();
 fs.writeFileSync(path.join(__dirname,'../assets/menu-layout-config.js'),render(project));
 console.log('Generated assets/menu-layout-config.js; run node scripts/build-game-entries.js next.');
}
module.exports={render};
